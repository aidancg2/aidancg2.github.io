import pandas as pd
import altair as alt

alt.data_transformers.disable_max_rows()

url = "https://raw.githubusercontent.com/UIUC-iSchool-DataViz/is445_data/main/bfro_reports_fall2022.csv"

df = pd.read_csv(url)

df.head()

print(df.shape)
print(df.columns.tolist())
df.info()

df.columns = df.columns.str.strip().str.lower()

df = df.dropna(subset=["state"]).copy()
df["state"] = df["state"].astype(str).str.strip()

state_counts = (
    df.groupby("state")
    .size()
    .reset_index(name="sightings")
    .sort_values("sightings", ascending=False)
)

df["date"] = pd.to_datetime(df["date"], errors="coerce")
df["year"] = df["date"].dt.year

year_counts = (
    df.dropna(subset=["year"])
    .groupby(["year", "state"])
    .size()
    .reset_index(name="sightings")
)

year_counts["year"] = year_counts["year"].astype(int)

print(state_counts.head())
print(year_counts.head())

top_states = state_counts.head(15)

chart1 = alt.Chart(top_states).mark_bar().encode(
    x=alt.X("sightings:Q", title="Number of Sightings"),
    y=alt.Y("state:N", sort="-x", title="State"),
    color=alt.Color(
        "sightings:Q",
        scale=alt.Scale(scheme="blues"),
        title="Sightings"
    ),
    tooltip=[
        alt.Tooltip("state:N", title="State"),
        alt.Tooltip("sightings:Q", title="Sightings")
    ]
).properties(
    title="Top 15 States with Bigfoot Sightings",
    width=600,
    height=400
)

chart1

states = sorted(year_counts["state"].unique().tolist())

dropdown = alt.binding_select(
    options=["All"] + states,
    name="Select State: "
)

state_select = alt.param(
    name="selected_state",
    value="All",
    bind=dropdown
)

chart2 = alt.Chart(year_counts).mark_line(
    point=True,
    color="steelblue"
).encode(
    x=alt.X("year:O", title="Year"),
    y=alt.Y("sum(sightings):Q", title="Number of Sightings"),
    tooltip=[
        alt.Tooltip("year:O", title="Year"),
        alt.Tooltip("sum(sightings):Q", title="Sightings")
    ]
).add_params(
    state_select
).transform_filter(
    (state_select == "All") |
    (alt.datum.state == state_select)
).properties(
    title="Bigfoot Sightings Over Time",
    width=650,
    height=350
)

chart2

chart1.save("bigfoot_states.html")
chart2.save("bigfoot_years.html")

